import { http } from './client'
import type { ListQuery } from './index'
import type { Paged } from './types'

export type MesFieldType =
  | 'str'
  | 'text'
  | 'int'
  | 'float'
  | 'bool'
  | 'enum'
  | 'ref'
  | 'date'
  | 'time'
  | 'datetime'
  | 'json'

export interface MesField {
  name: string
  /** API/DB column (`<name>_id` for refs) */
  column: string
  type: MesFieldType
  required: boolean
  /** conditionally required: {sibling field name: values}; '*' = any value */
  required_when: Record<string, unknown[]> | null
  /** blank -> backend copies this sibling field (e.g. code) */
  default_from: string | null
  /** blank -> generated by the backend */
  auto?: boolean
  /** maintained by the backend only (not editable) */
  system?: boolean
  enum: string | null
  ref: string | null
  list: boolean
  filter: boolean
  search: boolean
  default: unknown
  max_length: number | null
  help: boolean
  /** ref options are filtered by this sibling ref field (e.g. route) */
  depends: string | null
}

export interface MesEntity {
  code: string
  module: string
  url: string
  has_code: boolean
  tree: boolean
  versioned: boolean
  readonly: boolean
  parent: string | null
  children: string[]
  label_field: string
  sort_default: string
  natural_key: string[]
  read: string
  write: string
  can_read: boolean
  can_write: boolean
  fields: MesField[]
}

export interface MesMeta {
  modules: { code: string; order: number }[]
  entities: MesEntity[]
  enums: Record<string, string[]>
  /** extra MES permissions of the current user (e.g. mes.wo:release) */
  perms: string[]
}

export type MesRow = Record<string, unknown> & {
  id: string
  code?: string
  name?: string
  status?: string
  version?: number
  attrs?: Record<string, unknown> | null
}
export type MesTreeNode = MesRow & { children: MesTreeNode[] }

export interface MesAttrDef {
  code: string
  name: string
  data_type: 'string' | 'number' | 'boolean' | 'date' | 'select'
  required: boolean
  options: string[]
}

const seg = (code: string) => code.replace(/_/g, '-')
const base = (code: string) => `/mes/${seg(code)}`

/** Generic MES master-data client (/mes/<entity>). */
export const mesApi = {
  meta: () => http.get<MesMeta>('/mes/_meta').then((r) => r.data),
  attrs: (code: string) =>
    http.get<MesAttrDef[]>(`/mes/_attrs/${code}`).then((r) => r.data),
  list: (code: string, params?: ListQuery) =>
    http.get<Paged<MesRow>>(base(code), { params }).then((r) => r.data),
  tree: (code: string) =>
    http.get<MesTreeNode[]>(`${base(code)}/tree`).then((r) => r.data),
  get: (code: string, id: string) =>
    http.get<MesRow>(`${base(code)}/${id}`).then((r) => r.data),
  create: (code: string, body: Record<string, unknown>) =>
    http.post<MesRow>(base(code), body).then((r) => r.data),
  update: (code: string, id: string, body: Record<string, unknown>) =>
    http.patch<MesRow>(`${base(code)}/${id}`, body).then((r) => r.data),
  remove: (code: string, id: string) =>
    http.delete(`${base(code)}/${id}`).then((r) => r.data),
  setStatus: (code: string, id: string, status: string) =>
    http
      .post<MesRow>(`${base(code)}/${id}/status`, { status })
      .then((r) => r.data),
  newVersion: (code: string, id: string) =>
    http.post<MesRow>(`${base(code)}/${id}/new-version`).then((r) => r.data),
  exportXlsx: async (code: string) => {
    const r = await http.get<Blob>(`${base(code)}/export`, {
      responseType: 'blob',
    })
    const a = document.createElement('a')
    a.href = URL.createObjectURL(r.data)
    a.download = `${code}.xlsx`
    a.click()
    URL.revokeObjectURL(a.href)
  },
  importXlsx: (code: string, file: File) => {
    const fd = new FormData()
    fd.append('file', file)
    return http
      .post<{ created: number; updated: number }>(`${base(code)}/import`, fd)
      .then((r) => r.data)
  },
  convert: (from_uom: string, to_uom: string, value: number) =>
    http
      .get<{ value: number; path: string[] }>('/mes/_convert', {
        params: { from_uom, to_uom, value },
      })
      .then((r) => r.data),
  codePreview: (id: string, count = 3, context?: Record<string, unknown>) =>
    http
      .post<{ codes: string[] }>(`/mes/code-rule/${id}/preview`, {
        count,
        context,
      })
      .then((r) => r.data),
}

export const reorderRouteSteps = (routeId: string, stepIds: string[]) =>
  http
    .post<{ data: MesRow[] }>(`/mes/route/${routeId}/reorder`, {
      step_ids: stepIds,
    })
    .then((r) => r.data)

export interface StartPlanLot {
  lot_no: string
  qty: number
  slots: number[]
  wafer_ids: string[]
}
export interface StartPlan {
  work_order_id: string
  wo_status: string
  planned_qty: number
  started_qty: number
  max_qty: number
  remaining: number
  lot_size: number
  max_lot_size: number
  first_step_id: string | null
  first_step_seq: number | null
  site_id: string | null
  lots: StartPlanLot[]
}
export interface StartLotIn {
  qty: number
  carrier_id?: string | null
  slots?: number[]
  source_ref?: string | null
}

export const woApi = {
  transition: (id: string, action: string) =>
    http
      .post<MesRow>(`/mes/work-order/${id}/transition`, { action })
      .then((r) => r.data),
  plan: (id: string, body: { lot_size?: number; qty?: number }) =>
    http
      .post<StartPlan>(`/mes/work-order/${id}/start-plan`, body)
      .then((r) => r.data),
  start: (id: string, lots: StartLotIn[]) =>
    http
      .post<{ data: MesRow[] }>(`/mes/work-order/${id}/start`, { lots })
      .then((r) => r.data),
  undo: (id: string, lotIds?: string[]) =>
    http
      .post<{ undone: number }>(`/mes/work-order/${id}/undo-start`, {
        lot_ids: lotIds,
      })
      .then((r) => r.data),
}
